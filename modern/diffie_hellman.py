"""Finite-field Diffie-Hellman key agreement using cryptography.

Diffie-Hellman establishes a shared secret; it does not encrypt a message.
Use authenticated protocols (for example TLS) in production to prevent
man-in-the-middle attacks.
"""
from pathlib import Path
import warnings

from cryptography.utils import CryptographyDeprecationWarning
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import dh
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

# Newer versions of the cryptography library mark finite-field DH as
# deprecated (ECDH is preferred). CipherMind keeps DH only as a small
# teaching demo, so this one warning is hidden for this file only.
warnings.filterwarnings(
    "ignore",
    category=CryptographyDeprecationWarning,
    module=r"modern\.diffie_hellman",
)


def generate_dh_parameters(key_size=2048, generator=2):
    """Return PEM DH parameters.

    The default 2048-bit setting reuses the public parameter set bundled with
    CipherMind. Other supported sizes are generated by OpenSSL and may take
    noticeably longer. Parameters are public, not secret.
    """
    if not isinstance(key_size, int) or key_size < 2048:
        raise ValueError("DH parameters must be at least 2048 bits")
    if generator not in (2, 5):
        raise ValueError("Supported DH generators are 2 and 5")
    if key_size == 2048 and generator == 2:
        bundled = (
            Path(__file__).resolve().parent.parent
            / "data"
            / "dh_parameters_2048.pem"
        )
        if bundled.is_file():
            return bundled.read_bytes()
    parameters = dh.generate_parameters(generator=generator, key_size=key_size)
    return parameters.parameter_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.ParameterFormat.PKCS3,
    )


def generate_dh_keypair(parameters_pem):
    """Return (private_key_pem, public_key_pem) for supplied DH parameters."""
    if not isinstance(parameters_pem, bytes):
        raise TypeError("DH parameters must be PEM bytes")
    parameters = serialization.load_pem_parameters(parameters_pem)
    if not isinstance(parameters, dh.DHParameters):
        raise TypeError("PEM data does not contain DH parameters")
    private_key = parameters.generate_private_key()
    private_pem = private_key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    )
    public_pem = private_key.public_key().public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )
    return private_pem, public_pem


def derive_dh_shared_secret(private_key_pem, peer_public_key_pem):
    """Derive the raw shared secret from a local private key and peer public key."""
    if not isinstance(private_key_pem, bytes) or not isinstance(peer_public_key_pem, bytes):
        raise TypeError("DH keys must be PEM bytes")
    private_key = serialization.load_pem_private_key(private_key_pem, password=None)
    peer_key = serialization.load_pem_public_key(peer_public_key_pem)
    if not isinstance(private_key, dh.DHPrivateKey) or not isinstance(peer_key, dh.DHPublicKey):
        raise TypeError("Both keys must be Diffie-Hellman keys")
    return private_key.exchange(peer_key)


def derive_dh_session_key(shared_secret, length=32, salt=None, info=b"CipherMind DH session key"):
    """Use HKDF-SHA256 to derive key material from the DH shared secret."""
    if not isinstance(shared_secret, bytes) or not shared_secret:
        raise ValueError("Shared secret must be non-empty bytes")
    if not isinstance(length, int) or not 1 <= length <= 255 * 32:
        raise ValueError("HKDF output length must be between 1 and 8160 bytes")
    return HKDF(
        algorithm=hashes.SHA256(),
        length=length,
        salt=salt,
        info=info,
    ).derive(shared_secret)
